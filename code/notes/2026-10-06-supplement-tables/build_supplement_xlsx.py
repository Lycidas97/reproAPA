#!/usr/bin/env python3
"""Write Supplementary Tables S1-S8 as ONE xlsx with a uniform visual style (2026-10-06).

Layout
  Contents  - every table and sheet, with links, related supplementary figures, blocks and rows
  S1a..S8a  - one Excel sheet per cited sheet (40). Each source file is one data block: a caption line,
              an optional filter note, then an Excel Table (own filter buttons). Blocks run top to bottom,
              smallest first, so short summary/test tables are not buried under long member lists.
  Sources   - provenance of every block: source path, SHA-256, rows, row filter

Values are copied without recomputation; numbers keep full double precision (display is formatted only).
Inputs: table-plan.tsv, table-sources.tsv (layer == sheet), the FILTERS of build_workbooks.py.
Usage: build_supplement_xlsx.py [--preview N]   (--preview caps each block at N rows, for rendering checks)
"""
import argparse, csv, datetime, hashlib, json, re, sys
from pathlib import Path
import pandas as pd
import xlsxwriter
from xlsxwriter.utility import xl_rowcol_to_cell

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_workbooks as B  # noqa: E402  (FILTERS, src_path, typed, LABEL)
import amendments_1530 as A  # noqa: E402  (15:30 main-text check)
import amendments_1008 as A2  # noqa: E402  (2026-10-08 figure/table review)

OUTNAME = 'Supplementary_Tables_S1-S8.xlsx'
EXCEL_MAX = 1048575
MAXSTR = 32767

# ---------------------------------------------------------------- visual style (single source of truth)
FONT = 'Arial'
SIZE_BODY, SIZE_NOTE, SIZE_TITLE = 10, 9, 13
INK = '#1F2A36'        # body text
ACCENT = '#23415E'     # titles, captions, header fill
ACCENT_LIGHT = '#8FA9C4'
MUTED = '#6B7785'      # notes
BAND = '#F2F5F8'       # alternate data rows
GROUP = '#E3E9EF'      # table group rows on Contents
RULE = '#C5D0DB'       # thin rules
MAXW, MINW = 40, 7

GENERAL = ('Values are copied from the polyApipe v2-primary analysis outputs without recomputation. '
           'Each sheet holds one or more data blocks; each block is one source file, shown as a filterable table. '
           'Numbers are stored at full precision; integers are displayed as integers, other numbers with four '
           'decimals, or in scientific notation when their absolute value is below 0.001 or at least 1,000,000. '
           'The Sources sheet gives the file, SHA-256 and any row filter of every block. Unfiltered files and '
           'figure-plotting data are in the Supplementary Source Data package.')


def fig_label(s):
    return s.replace('-', '–') if s else ''


def build(preview=None, out=None):
    plan = list(csv.DictReader(open(HERE / 'table-plan.tsv'), delimiter='\t'))
    srcs = [r for r in csv.DictReader(open(HERE / 'table-sources.tsv'), delimiter='\t') if r['layer'] == 'sheet']
    out = out or HERE / OUTNAME
    wb = xlsxwriter.Workbook(out, {
        'strings_to_urls': False, 'strings_to_formulas': False, 'strings_to_numbers': False,
        'nan_inf_to_errors': True,
        'default_format_properties': {'font_name': FONT, 'font_size': SIZE_BODY, 'font_color': INK}})
    wb.set_properties({'title': 'Supplementary Tables S1–S8', 'comments': 'Generated by build_supplement_xlsx.py'})

    def F(**k):
        base = {'font_name': FONT, 'font_size': SIZE_BODY, 'font_color': INK, 'valign': 'top'}
        base.update(k)
        return wb.add_format(base)

    f_title = F(bold=True, font_size=SIZE_TITLE, font_color=ACCENT, valign='vcenter')
    f_sub = F(font_size=SIZE_NOTE, font_color=MUTED)
    f_link = F(font_size=SIZE_NOTE, font_color=ACCENT, underline=1)
    f_cap = F(bold=True, font_color=ACCENT)
    f_capn = F(font_color=MUTED)
    f_note = F(font_size=SIZE_NOTE, font_color=MUTED, italic=True)
    f_head = F(bold=True, font_color='#FFFFFF', bg_color=ACCENT, text_wrap=True, valign='vcenter',
               bottom=1, bottom_color=ACCENT, align='left', indent=1)
    f_head_num = F(bold=True, font_color='#FFFFFF', bg_color=ACCENT, text_wrap=True, valign='vcenter',
                   bottom=1, bottom_color=ACCENT, align='right', indent=1)
    f_para = F(font_size=SIZE_NOTE, font_color=MUTED, text_wrap=True)
    f_group = F(bold=True, font_color=ACCENT, bg_color=GROUP, top=1, top_color=RULE)
    f_groupf = F(bg_color=GROUP, top=1, top_color=RULE)
    # body formats: kind x band
    body = {}
    for band in (False, True):
        extra = {'bg_color': BAND, 'indent': 1} if band else {'indent': 1}
        body[('str', band)] = F(align='left', **extra)
        body[('int', band)] = F(num_format='0', **extra)
        body[('flt', band)] = F(num_format='0.0000', **extra)
        body[('sci', band)] = F(num_format='0.000E+00', **extra)
        body[('link', band)] = F(font_color=ACCENT, underline=1, align='left', **extra)
        body[('int', band)].set_align('right'); body[('flt', band)].set_align('right'); body[('sci', band)].set_align('right')
        body[('wrap', band)] = F(text_wrap=True, align='left', **extra)

    sheets = []                       # (table, plan row)
    for s in plan:
        s = dict(s)
        s['sheet_title'] = A2.TITLES.get(s['sheet'], A.TITLES.get(s['sheet'], s['sheet_title']))
        s['supp_figures'] = A2.SUPP_FIGURES.get(s['sheet'], s['supp_figures'])
        sheets.append(s)
    msha = A.manifest_sha()
    tables = list(dict.fromkeys(s['table'] for s in plan))
    ttitle = {s['table']: s['table_title'] for s in plan}

    contents = wb.add_worksheet('Contents')
    blocks_log, issues, prov = [], [], []
    n_tbl = 0
    plain = []
    sheet_rows = {}
    for si, s in enumerate(sheets):
        sh = s['sheet']
        ws = wb.add_worksheet(sh)
        ws.hide_gridlines(2)
        ws.set_tab_color(ACCENT if tables.index(s['table']) % 2 == 0 else ACCENT_LIGHT)
        ws.set_landscape(); ws.set_paper(9)
        if preview is None:
            ws.fit_to_pages(1, 0)
        ws.set_row(0, 22)
        ws.write_string(0, 0, f"Table {sh}. {s['sheet_title']}", f_title)
        sub = f"Part of Table {s['table']}: {ttitle[s['table']]}"
        if s['supp_figures']:
            sub += f"  ·  Related supplementary figures: {fig_label(s['supp_figures'])}"
        ws.write_string(1, 0, sub, f_sub)
        ws.write_url(2, 0, "internal:'Contents'!A1", f_link, string='← Contents')
        files = [r for r in srcs if r['sheet'] == sh and (sh, r['path']) not in A2.EXCLUDE]
        for (ash, apath) in A.ADD:                         # 15:30 additions from the bundle
            if ash == sh:
                files.append({'sheet': sh, 'path': apath, 'role': 'core_list', 'sha256': msha[apath]})
        loaded = []
        for k, r in enumerate(files):
            p = B.src_path(r)
            if hashlib.sha256(p.read_bytes()).hexdigest() != r['sha256']:
                issues.append(f"sha-mismatch {sh} {r['path']}")
            d = pd.read_csv(p, sep='\t', dtype=str, keep_default_na=False, na_filter=False,
                            compression='gzip' if r['path'].endswith('.gz') else None)
            n_src = len(d)
            notes = []
            flt = A.ADD.get((sh, r['path'])) or A.FILTER.get((sh, r['path']))
            if flt is None and r['path'] in B.FILTERS:
                flt = B.FILTERS[r['path']]
            if flt:
                notes.append('Rows shown: ' + flt[0])
                d = flt[1](d)
            for cname, fn, desc in A.ADD_COLS.get((sh, r['path']), []):
                d = d.copy(); d[cname] = fn(d); notes.append(desc)
            if (sh, r['path']) in A2.DROP_COLS:
                dcols, desc = A2.DROP_COLS[(sh, r['path'])]
                d = d.drop(columns=dcols); notes.append(desc)
            notes.extend(A2.NOTES.get((sh, r['path']), []))
            r = dict(r, inputs=[(r['path'], r['sha256'])])
            loaded.append((len(d), k, r, d, n_src, notes))
        for j, (name, fn, desc, inputs) in enumerate(A.DERIVED.get(sh, [])):
            d = fn()
            r = {'sheet': sh, 'path': name, 'role': 'derived', 'sha256': '',
                 'inputs': [(x, A.sha(A.ROOT / x)) for x in inputs]}
            loaded.append((len(d), 1000 + j, r, d, len(d), [desc]))
        loaded.sort(key=lambda x: (x[0], x[1]))            # smallest block first
        widths = {}
        row = 4
        nb = len(loaded)
        for bi, (n, k, r, d, n_src, notes) in enumerate(loaded, 1):
            label = sh if nb == 1 else f'{sh}.{bi}'
            stem = Path(r['path']).name
            for ext in ('.gz', '.tsv'):
                stem = stem[:-len(ext)] if stem.endswith(ext) else stem
            stem = re.sub(r'^S\d+-', '', stem)
            if r['path'] in B.LABEL:
                stem = f"{stem} ({B.LABEL[r['path']]})"
            shown = d if preview is None else d.head(preview)
            rowtxt = f'{n:,} rows' + (f' (of {n_src:,} in the source file)' if n != n_src else '')
            # one rich-text caption cell (spills right over empty cells): bold label + muted row count
            ws.write_rich_string(row, 0, f_cap, f'{label}  {stem}', f_capn, f'    {rowtxt}')
            row += 1
            for nt in notes:
                ws.write_string(row, 0, nt, f_note)
                row += 1
            hdr_row = row
            kinds = B.typed(d)
            cols = list(d.columns)
            ncol = len(cols)
            vals = shown.to_numpy()
            last = hdr_row + max(len(shown), 1)
            if last > EXCEL_MAX:
                issues.append(f'sheet too long {sh}'); break
            # per-column kind: str / int / flt (flt display is 4 decimals, so width is capped accordingly)
            colkind = []
            for j, c in enumerate(cols):
                if kinds[j] != 'num':
                    colkind.append('str'); continue
                v = pd.to_numeric(d[c][d[c] != ''])
                colkind.append('int' if len(v) and (v % 1 == 0).all() and (v.abs() < 1e15).all() else 'flt')
            # Excel Tables need case-insensitively unique headers (e.g. 'N' and 'n' in the ORA tables);
            # such blocks keep their exact headers as a plain styled range without filter buttons
            low = [c.lower() for c in cols]
            as_table = len(set(low)) == len(low)
            if as_table:
                n_tbl += 1
                ws.add_table(hdr_row, 0, last, ncol - 1, {
                    'name': f'T_{sh}_{bi}', 'style': None, 'autofilter': True,
                    'columns': [{'header': c, 'header_format': f_head if colkind[j] == 'str' else f_head_num}
                                for j, c in enumerate(cols)]})
            else:
                plain.append(label)
            for j, c in enumerate(cols):
                hf = f_head if colkind[j] == 'str' else f_head_num
                ws.write_string(hdr_row, j, c, hf)
                dw = 12 if colkind[j] == 'flt' else max([0] + [len(x) for x in d[c].head(300)])
                w = max(len(c) * 1.1, dw) + 3
                widths[j] = max(widths.get(j, MINW), min(w, MAXW))
            trunc = 0
            for ri, rv in enumerate(vals):
                rr = hdr_row + 1 + ri
                band = ri % 2 == 1
                for j, v in enumerate(rv):
                    ck = colkind[j]
                    if v == '':
                        ws.write_blank(rr, j, None, body[('str', band)])
                    elif ck == 'str':
                        if len(v) > MAXSTR:
                            v = v[:MAXSTR]; trunc += 1
                        ws.write_string(rr, j, v, body[('str', band)])
                    else:
                        x = float(v)
                        if x != x or x in (float('inf'), float('-inf')):
                            ws.write_string(rr, j, v, body[('str', band)])
                        elif ck == 'int':
                            ws.write_number(rr, j, x, body[('int', band)])
                        else:
                            a = abs(x)
                            fk = 'flt' if (a == 0 or 1e-3 <= a < 1e6) else 'sci'
                            ws.write_number(rr, j, x, body[(fk, band)])
            if trunc:
                issues.append(f'truncated {trunc} cells {label}')
            blocks_log.append(dict(sheet=sh, block=label, path=r['path'], role=r['role'], header_row=hdr_row + 1,
                                   rows=len(shown), rows_filtered=n, rows_source=n_src, columns=ncol,
                                   excel_table=as_table))
            short = lambda x: x.replace(A.B_, '', 1)
            if r['role'] == 'derived':
                ptxt = 'derived from: ' + '; '.join(short(x) for x, _ in r['inputs'])
            else:
                ptxt = r['path']
            prov.append(dict(block=label, sheet=sh, path=ptxt, rows=n, rows_src=n_src, filter=' '.join(notes),
                             sha='; '.join(h for _, h in r['inputs'])))
            row = last + 3
        for j, w in widths.items():
            ws.set_column(j, j, w)
        ws.freeze_panes(3, 0)
        sheet_rows[sh] = (nb, sum(x[0] for x in loaded))

    # ------------------------------------------------------------ Contents
    c = contents
    f_rows = {b: F(num_format='#,##0', align='right', indent=1, **({'bg_color': BAND} if b else {})) for b in (False, True)}
    c.hide_gridlines(2); c.set_tab_color('#7F8B97'); c.activate(); c.set_first_sheet()
    c.set_landscape(); c.set_paper(9); c.fit_to_pages(1, 0)
    c.set_column(0, 0, 10); c.set_column(1, 1, 58); c.set_column(2, 2, 30); c.set_column(3, 4, 13)
    c.set_row(0, 22)
    c.write_string(0, 0, 'Supplementary Tables S1–S8', f_title)
    c.merge_range(1, 0, 1, 4, GENERAL, f_para); c.set_row(1, 64)
    c.merge_range(2, 0, 2, 4, A2.CONTRAST_KEY, f_para); c.set_row(2, 84)
    hr = 4
    for j, h in enumerate(['Sheet', 'Title', 'Related supplementary figures', 'Data blocks', 'Rows']):
        c.write_string(hr, j, h, f_head if j < 3 else f_head_num)
    r = hr
    i = 0
    for t in tables:
        r += 1
        c.write_string(r, 0, f'Table {t}', f_group)
        c.write_string(r, 1, ttitle[t], f_group)
        for j in (2, 3, 4):
            c.write_blank(r, j, None, f_groupf)
        for s in [x for x in sheets if x['table'] == t]:
            r += 1
            band = i % 2 == 1; i += 1
            nb, nr = sheet_rows[s['sheet']]
            c.write_url(r, 0, f"internal:'{s['sheet']}'!A1", body[('link', band)], string=s['sheet'])
            c.write_string(r, 1, s['sheet_title'], body[('str', band)])
            c.write_string(r, 2, fig_label(s['supp_figures']), body[('str', band)])
            c.write_number(r, 3, nb, body[('int', band)])
            c.write_number(r, 4, nr, f_rows[band])
    c.freeze_panes(hr + 1, 0)

    # ------------------------------------------------------------ Sources
    p = wb.add_worksheet('Sources')
    p.hide_gridlines(2); p.set_tab_color('#7F8B97')
    p.set_landscape(); p.set_paper(9); p.fit_to_pages(1, 0)
    p.set_row(0, 22)
    p.write_string(0, 0, 'Sources of the data blocks', f_title)
    p.write_string(1, 0, A2.SOURCES_NOTE, f_sub)
    p.write_url(2, 0, "internal:'Contents'!A1", f_link, string='← Contents')
    heads = ['Block', 'Source file', 'Rows shown', 'Rows in source file', 'Row filter or derivation', 'SHA-256 of source file']
    hfmt = [f_head, f_head, f_head_num, f_head_num, f_head, f_head]
    hr = 4
    p.add_table(hr, 0, hr + len(prov), len(heads) - 1, {
        'name': 'T_Sources', 'style': None, 'autofilter': True,
        'columns': [{'header': h, 'header_format': hfmt[j]} for j, h in enumerate(heads)]})
    for j, h in enumerate(heads):
        p.write_string(hr, j, h, hfmt[j])
    for ri, x in enumerate(prov):
        band = ri % 2 == 1; rr = hr + 1 + ri
        p.write_url(rr, 0, f"internal:'{x['sheet']}'!A1", body[('link', band)], string=x['block'])
        p.write_string(rr, 1, x['path'], body[('str', band)])
        p.write_number(rr, 2, x['rows'], body[('int', band)])
        p.write_number(rr, 3, x['rows_src'], body[('int', band)])
        if x['filter']:
            p.write_string(rr, 4, x['filter'], body[('wrap', band)])
        else:
            p.write_blank(rr, 4, None, body[('str', band)])
        p.write_string(rr, 5, x['sha'], body[('str', band)])
    for j, w in enumerate([9, 62, 11, 12, 60, 66]):
        p.set_column(j, j, w)
    p.freeze_panes(hr + 1, 0)
    wb.close()
    return blocks_log, issues, n_tbl


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--preview', type=int)
    ap.add_argument('--out')
    a = ap.parse_args()
    out = Path(a.out) if a.out else None
    blocks, issues, n_tbl = build(a.preview, out)
    if a.preview is None:
        with open(HERE / 'supplement-blocks.tsv', 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(blocks[0]), delimiter='\t')
            w.writeheader(); w.writerows(blocks)
        json.dump({'generated': datetime.datetime.now().isoformat(timespec='seconds'), 'blocks': len(blocks),
                   'excel_tables': n_tbl, 'issues': issues}, open(HERE / 'supplement-build.json', 'w'), indent=1)
    print('blocks', len(blocks), 'tables', n_tbl, 'issues', issues)
    return 1 if issues else 0


if __name__ == '__main__':
    sys.exit(main())
